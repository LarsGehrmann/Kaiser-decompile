"""Write a Markdown overview of an NE executable's layout.

Usage: python3 -I tools/ne_info.py Kaiser/kaiser.exe > docs/ne-layout.md
"""
import os
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ne import NEFile, load_spec  # noqa: E402


def main():
    f = NEFile(sys.argv[1])
    p = print
    p(f'# NE layout of `{os.path.basename(f.path)}`\n')
    p('Generated by `tools/ne_info.py`. Manual notes belong in '
      '`docs/segments.md`.\n')
    p('## Header\n')
    p('| Field | Value |\n|---|---|')
    p(f'| Module name | {f.resident_names[0][1]} |')
    p(f'| Description | {f.nonresident_names[0][1]} |')
    p(f'| Linker | {f.linker_ver}.{f.linker_rev} |')
    p(f'| Flags | 0x{f.flags:04x} |')
    p(f'| Entry point (CS:IP) | seg {f.entry_point[0]} : '
      f'0x{f.entry_point[1]:04x} |')
    p(f'| Initial stack (SS:SP) | seg {f.initial_stack[0]} : '
      f'0x{f.initial_stack[1]:04x} |')
    p(f'| Auto data segment | {f.autodata_seg} |')
    p(f'| Heap / stack size | {f.heap_size} / {f.stack_size} |')
    p(f'| Segments | {f.seg_count} |')
    p(f'| Entry table ordinals | {len(f.entries)} |')
    p(f'| Alignment shift | {f.align_shift} |')
    p(f'| Module references | {", ".join(f.modules)} |')
    p()

    p('## Segments\n')
    p('| # | File offset | Length | Min alloc | Flags | Relocs | '
      'Entries | Import sites |')
    p('|---|---|---|---|---|---|---|---|')
    entries_per_seg = Counter(s for s, _, _ in f.entries.values())
    for s in f.segments:
        imp_sites = sum(len(r.sites) for r in s.relocs
                        if r.kind in ('IMPORTORDINAL', 'IMPORTNAME'))
        p(f'| {s.index} | 0x{s.file_offset:05x} | {s.length} | '
          f'{s.min_alloc} | {s.flag_str()} | {len(s.relocs)} | '
          f'{entries_per_seg.get(s.index, 0)} | {imp_sites} |')
    p()

    p('## Imported API functions\n')
    p('Fixup sites per function, and which segments call it.\n')
    specs = {m: load_spec(m) for m in set(f.modules)}
    users = defaultdict(set)
    for s in f.segments:
        for r in s.relocs:
            if r.kind in ('IMPORTORDINAL', 'IMPORTNAME'):
                users[r.target].add(s.index)
    used = f.imported_functions()
    for module in sorted(set(f.modules)):
        rows = [(k, v) for k, v in used.items() if k[0] == module]
        if not rows:
            continue
        p(f'### {module}\n')
        p('| Ordinal | Name | Sites | Segments |\n|---|---|---|---|')
        for (mod, ordinal), n in sorted(rows, key=lambda kv: str(kv[0][1])):
            name = specs[mod].get(ordinal, '?') if isinstance(
                ordinal, int) else ordinal
            segs = ', '.join(str(x) for x in sorted(users[(mod, ordinal)]))
            p(f'| {ordinal} | {name} | {n} | {segs} |')
        p()

    p('## Resources\n')
    p('| Type | Count | Bytes |\n|---|---|---|')
    by_type = defaultdict(list)
    for r in f.resources:
        by_type[r.type_name].append(r)
    for t, rs in sorted(by_type.items()):
        p(f'| {t} | {len(rs)} | {sum(r.length for r in rs)} |')
    p()


if __name__ == '__main__':
    main()
