"""Generate port/src/kaisertypes.pas from tools/kaiser_structs.py.

Every record is a packed record with exactly the original size; bytes between
known fields become padding arrays, so savegames can be read and written
unchanged. Re-run after changing kaiser_structs.py.
Usage: python3 -I tools/gen_pascal_types.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kaiser_structs as ks  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'port', 'src', 'kaisertypes.pas')

SIZES = {'u8': 1, 's8': 1, 'u16': 2, 's16': 2, 's32': 4, 'real': 6}
PASCAL = {'u8': 'Byte', 's8': 'ShortInt', 'u16': 'Word', 's16': 'SmallInt',
          's32': 'LongInt', 'real': 'TReal48'}
# fields that hold arrays of units instead of raw bytes
UNIT_ARRAYS = {'army1', 'army2'}


def size_of(typ):
    if typ in SIZES:
        return SIZES[typ]
    return int(re.sub(r'\D', '', typ))


def pascal_type(name, typ):
    if name in UNIT_ARRAYS:
        return 'array[1..8] of TUnit'
    if typ in PASCAL:
        return PASCAL[typ]
    n = size_of(typ)
    if typ.startswith('cstr'):
        return f'array[0..{n - 1}] of Char'
    return f'array[0..{n - 1}] of Byte'


RESERVED = {'type', 'label', 'file', 'set', 'object', 'record', 'string',
            'unit', 'end', 'begin', 'case', 'of', 'var', 'const', 'in', 'is',
            'out', 'packed', 'program', 'array', 'function', 'procedure',
            'with', 'do', 'to', 'downto', 'repeat', 'until', 'while', 'for',
            'if', 'then', 'else', 'nil', 'not', 'and', 'or', 'xor', 'div',
            'mod', 'shl', 'shr', 'goto', 'class', 'property', 'interface'}


def ident(name):
    # Pascal identifiers: CamelCase, '_q' (unconfirmed) kept as suffix Q
    parts = name.split('_')
    q = parts[-1] == 'q'
    if q:
        parts = parts[:-1]
    s = ''.join(p[:1].upper() + p[1:] for p in parts if p)
    if s.lower() in RESERVED:
        s = 'Unit' + s if s.lower() == 'type' else s + '_'
    return s + ('Q' if q else '')


def record(name, fields, size):
    lines = [f'  {name} = packed record']
    pos = 0
    for off, typ, fname, comment in fields:
        if off > pos:
            lines.append(f'    Pad{pos:03X}: array[0..{off - pos - 1}] of Byte;')
        elif off < pos:
            raise ValueError(f'{name}: field {fname} overlaps at 0x{off:x}')
        c = f'  {{ +0x{off:03x} {comment} }}' if comment else f'  {{ +0x{off:03x} }}'
        c = c.replace('}', ')', c.count('}') - 1) if c.count('}') > 1 else c
        lines.append(f'    {ident(fname)}: {pascal_type(fname, typ)};{c}')
        pos = off + size_of(typ)
    if pos < size:
        lines.append(f'    Pad{pos:03X}: array[0..{size - pos - 1}] of Byte;')
    lines.append('  end;')
    return '\n'.join(lines)


def main():
    header = ('{ Generated by tools/gen_pascal_types.py from tools/kaiser_structs.py.\n'
              '  Do not edit by hand. }\n'
              'unit KaiserTypes;\n\n{$mode objfpc}{$H+}\n\ninterface\n\n'
              'const\n'
              f'  HeaderSize = ${ks.HEADER_SIZE:X};\n'
              f'  PlayerSize = ${ks.PLAYER_SIZE:X};\n'
              f'  UnitSize = ${ks.UNIT_SIZE:X};\n'
              f'  ExtraSize = ${ks.EXTRA_SIZE:X};\n'
              '  MaxPlayers = 10;\n\n'
              'type\n'
              '  { Borland Pascal 6-byte Real, stored unchanged }\n'
              '  TReal48 = packed array[0..5] of Byte;\n\n')
    body = '\n\n'.join([
        record('TUnit', ks.UNIT, ks.UNIT_SIZE),
        record('TPlayer', ks.PLAYER, ks.PLAYER_SIZE),
        record('TGameHeader', ks.HEADER, ks.HEADER_SIZE),
    ])
    footer = ('\n\n  TPlayers = array[0..MaxPlayers - 1] of TPlayer;\n\n'
              'implementation\n\n'
              'initialization\n'
              '  Assert(SizeOf(TUnit) = UnitSize);\n'
              '  Assert(SizeOf(TPlayer) = PlayerSize);\n'
              '  Assert(SizeOf(TGameHeader) = HeaderSize);\n'
              'end.\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(header + body + footer)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
