"""Generate port/src/kaisermaps.pas: the battlefields (MAPDATA resources 1..20)
of kaiser.exe, 165 bytes each (15 columns x 11 rows, column-major).
1..10: the cities by country, 11..20: the field battles."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ne import NEFile  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'port', 'src', 'kaisermaps.pas')


def main():
    ne = NEFile(os.path.join(ROOT, 'Kaiser', 'kaiser.exe'))
    maps = {r.res_id: r.data[:165] for r in ne.resources if r.type_id == 'MAPDATA'}
    lines = ['{ Generated by tools/gen_pascal_maps.py from the MAPDATA resources of',
             '  kaiser.exe. Do not edit by hand. }',
             'unit KaiserMaps;', '', 'interface', '', 'type',
             '  TBattleMap = array[0..164] of Byte;   { column-major: x * 11 + y }', '',
             'const', '  { 1..10 cities by country, 11..20 field battles }',
             '  MapData: array[1..20] of TBattleMap = (']
    for i in range(1, 21):
        b = maps[i]
        rows = [', '.join(f'${x:02X}' for x in b[k:k + 15]) for k in range(0, 165, 15)]
        body = ',\n     '.join(rows)
        lines.append(f'    ({body}){"," if i < 20 else ""}')
    lines += ['  );', '', 'implementation', '', 'end.', '']
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
