"""Find fixed-width string tables (array of Pascal array[..] of char) in DS.

Borland Pascal stores typed constants like
    SpellNames: array[0..12] of array[0..24] of Char = ('Nichts', ...)
as consecutive zero-padded strings with a constant stride. This scans the
data segment for runs of >= MIN_RUN such strings and prints each table
with its DS offset, stride and entries.

Usage: python3 -I tools/string_tables.py Kaiser/kaiser.exe > docs/data-tables.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ne import NEFile  # noqa: E402

MIN_RUN = 4
STRIDES = range(6, 64)


def is_text(b):
    return all(32 <= c < 127 or c >= 0xC0 or c in (0xB4, 0xDF) for c in b)


def entry(ds, off, stride):
    raw = ds[off:off + stride]
    if len(raw) < stride:
        return None
    s = raw.split(b'\0')[0]
    # zero-terminated inside the slot, then only zero bytes
    if len(s) >= stride or not is_text(s) or any(raw[len(s):]):
        return None
    return s.decode('cp1252')


def find_tables(ds):
    tables, taken = [], set()
    for stride in STRIDES:
        off = 0
        while off < len(ds) - stride * MIN_RUN:
            if off in taken:
                off += 1
                continue
            run = []
            p = off
            while True:
                e = entry(ds, p, stride)
                if e is None:
                    break
                run.append(e)
                p += stride
            texts = [e for e in run if len(e) >= 2]
            # padded tables: several entries end well before the slot end
            padded = sum(1 for e in run if len(e) <= stride - 3)
            if (len(run) >= MIN_RUN and run[0] and len(texts) >= MIN_RUN
                    and len(texts) * 2 >= len(run) and padded * 2 >= len(run)):
                tables.append((off, stride, run))
                taken.update(range(off, p))
                off = p
            else:
                off += 1
    return sorted(tables)


def main():
    ds = NEFile(sys.argv[1]).segments[-1].data
    print('# String tables in the data segment\n')
    print('Generated by `tools/string_tables.py`: runs of zero-padded strings with '
          'a constant stride (Pascal `array of array[..] of Char` constants). '
          'Index 0 is the first entry.\n')
    for off, stride, run in find_tables(ds):
        while run and not run[-1]:
            run.pop()
        print(f'## DS:{off:04x}  stride {stride}, {len(run)} entries\n')
        print(', '.join(f'{i}={e!r}' for i, e in enumerate(run)) + '\n')


if __name__ == '__main__':
    main()
