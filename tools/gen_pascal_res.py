"""Generate port/src/kaiserres.pas: the string table resources of kaiser.exe
and a LoadString with the semantics of USER.LoadString (copy at most
MaxLen - 1 characters plus #0, return the length; 0 for unknown ids).
Strings are kept as raw CP1252 bytes.
Usage: python3 -I tools/gen_pascal_res.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ne import NEFile  # noqa: E402

ROOT = os.path.dirname(HERE)
EXE = os.path.join(ROOT, 'Kaiser', 'kaiser.exe')
OUT = os.path.join(ROOT, 'port', 'src', 'kaiserres.pas')
RT_STRING = 6


def pascal_literal(raw):
    """Raw bytes as a Pascal string expression (printable ASCII quoted, rest #nnn)."""
    parts, run = [], ''
    for b in raw:
        if 32 <= b < 127 and b != 39:
            run += chr(b)
        else:
            if run:
                parts.append(f"'{run}'")
                run = ''
            parts.append(f'#{b}')
    if run:
        parts.append(f"'{run}'")
    return ''.join(parts) or "''"


def main():
    strings = {}
    for r in NEFile(EXE).resources:
        if r.type_id != RT_STRING:
            continue
        p = 0
        for i in range(16):
            if p >= len(r.data):
                break
            n = r.data[p]
            if n:
                strings[(r.res_id - 1) * 16 + i] = r.data[p + 1:p + 1 + n]
            p += 1 + n
    ids = sorted(strings)
    lines = [
        '{ Generated by tools/gen_pascal_res.py from the string table resources',
        '  of Kaiser/kaiser.exe. Do not edit by hand. }',
        'unit KaiserRes;', '', '{$mode objfpc}{$H+}', '', 'interface', '',
        '{ USER.LoadString: copies at most MaxLen - 1 characters and a #0 to Buf,',
        '  returns the number of characters copied (0 if there is no such string) }',
        'function LoadString(ID: Word; Buf: PChar; MaxLen: Integer): Integer;', '',
        '{ the raw (CP1252) text of a string resource, empty if there is none }',
        'function ResString(ID: Word): RawByteString;', '',
        'implementation', '',
        'const',
        f'  ResCount = {len(ids)};',
        '  ResIds: array[0..ResCount - 1] of Word = (',
    ]
    for k in range(0, len(ids), 12):
        tail = ',' if k + 12 < len(ids) else ');'
        lines.append('    ' + ', '.join(str(i) for i in ids[k:k + 12]) + tail)
    lines.append('  ResTexts: array[0..ResCount - 1] of ShortString = (')
    for k, i in enumerate(ids):
        tail = ',' if k + 1 < len(ids) else ');'
        lines.append(f'    {pascal_literal(strings[i])}{tail}  {{ {i} }}')
    lines += [
        '',
        'function Find(ID: Word): Integer;',
        'var',
        '  Lo, Hi, Mid: Integer;',
        'begin',
        '  Lo := 0;',
        '  Hi := ResCount - 1;',
        '  while Lo <= Hi do',
        '  begin',
        '    Mid := (Lo + Hi) div 2;',
        '    if ResIds[Mid] = ID then',
        '      Exit(Mid);',
        '    if ResIds[Mid] < ID then',
        '      Lo := Mid + 1',
        '    else',
        '      Hi := Mid - 1;',
        '  end;',
        '  Result := -1;',
        'end;',
        '',
        'function LoadString(ID: Word; Buf: PChar; MaxLen: Integer): Integer;',
        'var',
        '  K: Integer;',
        'begin',
        '  Result := 0;',
        '  K := Find(ID);',
        '  if (K < 0) or (MaxLen <= 0) then',
        '    Exit;',
        '  Result := Length(ResTexts[K]);',
        '  if Result > MaxLen - 1 then',
        '    Result := MaxLen - 1;',
        '  Move(ResTexts[K][1], Buf^, Result);',
        '  Buf[Result] := #0;',
        'end;',
        '',
        'function ResString(ID: Word): RawByteString;',
        'var',
        '  K: Integer;',
        'begin',
        '  K := Find(ID);',
        '  if K < 0 then',
        "    Result := ''",
        '  else',
        '    Result := ResTexts[K];',
        'end;',
        '',
        'end.',
    ]
    with open(OUT, 'w', encoding='ascii') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(ids), 'strings')


if __name__ == '__main__':
    main()
