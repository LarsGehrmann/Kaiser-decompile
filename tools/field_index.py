"""Index which functions touch which player-record / game-header fields.

Scans the decompiled text in ghidra_out/decomp/ for
  * 0x6d5 + 0xNN        player record field (records start at Self+0x41,
                        so the field offset is NN - 0x41)
  DAT_10d0_61xx / 62xx  game header field (header = DS:6108, 0x295 bytes)
and classifies each hit as write ('=' assignment, ++/--) or read.

Field names come from tools/kaiser_structs.py.
Usage: python3 -I tools/field_index.py > docs/field-index.md
       (--players adds a rough, base-ambiguous player-record section)
"""
import os
import re
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from kaiser_structs import HEADER_FIELDS, PLAYER_FIELDS  # noqa: E402

DECOMP = os.path.join(os.path.dirname(HERE), 'ghidra_out', 'decomp')
PLAYER_BASE = 0x41
HEADER_DS = 0x6108
HEADER_SIZE = 0x295

PLAYER_RE = re.compile(r'\* 0x6d5 \+ (0x[0-9a-f]+|\d+)\)?')
HEADER_RE = re.compile(r'DAT_10d0_([0-9a-f]{4})')
WRITE_RE = re.compile(r'^\s*[^=!<>]*?(=[^=]|\+\+|--)')


def field_name(fields, off):
    for f_off, typ, name in fields:
        size = {'u8': 1, 's8': 1, 's16': 2, 'u16': 2, 's32': 4,
                'real': 6}.get(typ, int(re.sub(r'\D', '', typ) or 1))
        if f_off <= off < f_off + size:
            return name if f_off == off else f'{name}+{off - f_off}'
    return ''


def scan():
    player = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    header = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for fname in sorted(os.listdir(DECOMP)):
        src = open(os.path.join(DECOMP, fname), encoding='utf-8').read()
        for part in re.split(r'(?m)^// ==== ', src)[1:]:
            func = part.split(' ====', 1)[0]
            for line in part.splitlines()[1:]:
                is_write = bool(WRITE_RE.match(line))
                lhs = line.split('=', 1)[0] if is_write else ''
                for m in PLAYER_RE.finditer(line):
                    off = int(m.group(1), 0) - PLAYER_BASE
                    if off < 0:
                        continue
                    w = is_write and m.start() < len(lhs)
                    player[off][func][0 if w else 1] += 1
                for m in HEADER_RE.finditer(line):
                    off = int(m.group(1), 16) - HEADER_DS
                    if not 0 <= off < HEADER_SIZE:
                        continue
                    w = is_write and m.start() < len(lhs)
                    header[off][func][0 if w else 1] += 1
    return player, header


def emit(title, data, fields):
    print(f'\n## {title}\n')
    print('| Offset | Known as | Functions (writes/reads) |')
    print('|---|---|---|')
    for off in sorted(data):
        funcs = sorted(data[off].items(), key=lambda kv: -sum(kv[1]))
        cells = ', '.join(f'{f} ({w}/{r})' for f, (w, r) in funcs[:8])
        more = f' … +{len(funcs) - 8}' if len(funcs) > 8 else ''
        print(f'| 0x{off:03x} | {field_name(fields, off)} | {cells}{more} |')


def main():
    player, header = scan()
    print('# Field usage index\n')
    print('Generated by `tools/field_index.py` from `ghidra_out/decomp/`. '
          'Text-based: counts are approximate, but every listed function '
          'really touches the field.')
    emit('Game header (DS:6108)', header, HEADER_FIELDS)
    if '--players' in sys.argv:
        # Unreliable: functions index the player array either from the
        # main window (records at +0x41) or from the array itself, and the
        # text cannot tell which. Player fields need Ghidra struct typing.
        emit('Player record (assuming Self+0x41 + i*0x6d5)', player,
             PLAYER_FIELDS)


if __name__ == '__main__':
    main()
